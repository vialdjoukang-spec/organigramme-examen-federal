def liste_html() -> str:
    lignes = []
    for i, nom, _e in DX:
        lignes.append(f"<h2>DX.{i} — {nom}</h2>\n")
    intro = (
        "<h2>Liste canonique des dix diagnostics</h2>\n"
        "<p>L'ordre suit les proportions publiées, de la forme primaire vers les causes secondaires, "
        "puis les entités dont la fréquence n'est pas quantifiée dans les sources lues. "
        "Les rangs d'exclusion, eux, ouvrent l'algorithme.</p>\n"
    )
    return intro + "".join(lignes)
