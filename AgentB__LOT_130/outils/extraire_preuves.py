def coupe(blob: str, a: str, b: str) -> str:
    a, b = norm(a), norm(b)
    i = blob.find(a)
    if i < 0:
        raise SystemExit(f"ancre début absente: {a[:80]}")
    j = blob.find(b, i)
    if j < 0:
        raise SystemExit(f"ancre fin absente: {b[:80]} | après {a[:40]}")
    return blob[i:j + len(b)]

def main() -> None:
    rows = []
    for pid, fn, a, b, meta in DECOUPES:
        txt = coupe(SRC[fn], a, b)
        if txt not in SRC[fn]:
            raise SystemExit(f"vérif échouée {pid}")
        rows.append({"id": pid, "fichier": fn, "texte": txt, **meta})
    OUT.write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows), encoding="utf-8")
    print(f"{len(rows)} preuves, {OUT.stat().st_size} octets")

if __name__ == "__main__":
    main()
