"""Glossaire de fenêtres : mécanisme, exemple chiffré, piège. Faits limités aux sources lues."""
from html import escape

def fen(title, paragraphs, source):
    inner = "".join(f"<p style='margin:4px 0 6px;'>{x}</p>" for x in paragraphs)
    return (
        "<details style='margin:8px 0;border-left:4px solid #0e6655;background:#e8f8f5;"
        "padding:6px 10px;'><summary style='cursor:pointer;font-weight:bold;color:#0e6655;'>"
        f"{escape(title)}</summary><div style='margin-top:6px;'>{inner}"
        f"<em>Source : {escape(source)}.</em></div></details>"
    )

def g(term, mech, example, trap, source):
    return fen("Glossaire — " + term, [
        mech, example, "Piège d'examen : " + trap,
    ], source)

def pack(rows):
    out = []
    for r in rows:
        if len(r) == 5:
            out.append(g(*r))
            continue
        title, *rest = r
        source = rest[-1]
        out.append(fen(title, list(rest[:-1]), source))
    return "".join(out)

